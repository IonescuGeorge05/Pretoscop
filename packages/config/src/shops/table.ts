import type { ShopConfig } from './schema';

const CHANNEL: Record<ShopConfig['access_mode'], string> = {
  direct: 'C (polite crawl)',
  assisted: 'U (assisted access)',
  feed_only: 'F/M (feed)',
  off: '—',
};

/** Markdown table of the registry, embedded in docs/06-retailer-targets.md by `pnpm shops:table`. */
export function renderShopsTable(shops: ShopConfig[]): string {
  const rows = shops.map((s) => {
    const enabled = s.sources.filter((x) => x.enabled).length;
    const kinds = [...new Set(s.sources.map((x) => x.kind))].join(', ') || '—';
    const aff = s.affiliate
      ? `${s.affiliate.network} (${s.affiliate.comparator_policy}${s.affiliate.status !== 'none' ? `, ${s.affiliate.status}` : ''})`
      : '—';
    const ship = s.shipping.verified ? 'verified' : 'to verify';
    return `| ${s.name} | ${s.domain} | ${s.status} | ${CHANNEL[s.access_mode]} | ${s.trust_tier} | ${aff} | ${enabled}/${s.sources.length} (${kinds}) | ${ship} | ${(s.notes ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ').slice(0, 140)} |`;
  });
  return [
    '| Shop | Domain | Status | Channel | Trust tier | Affiliate (comparator policy) | Sources enabled/total | Shipping rules | Notes |',
    '|---|---|---|---|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

export const TABLE_START = '<!-- shops:table:start (generated by `pnpm shops:table`; edit packages/config/shops/*.yaml instead) -->';
export const TABLE_END = '<!-- shops:table:end -->';

/** Replaces (or appends) the generated section of a markdown document. */
export function embedTable(markdown: string, table: string, generatedAt: string): string {
  const block = `${TABLE_START}\n\n_Generated ${generatedAt} from the registry._\n\n${table}\n\n${TABLE_END}`;
  const start = markdown.indexOf(TABLE_START);
  const end = markdown.indexOf(TABLE_END);
  if (start >= 0 && end > start) return markdown.slice(0, start) + block + markdown.slice(end + TABLE_END.length);
  return `${markdown.trimEnd()}\n\n## Registry snapshot (generated)\n\n${block}\n`;
}
