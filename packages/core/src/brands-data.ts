/**
 * Brand dictionary seed (electronics, IT, appliances, small appliances, personal care, tools).
 * Edit freely: add aliases when a shop spells a brand differently, product lines when titles name
 * a line without the brand. `brands.test.ts` checks there are at least 300 brands and no alias
 * points to two brands.
 *
 * Flags:
 * - `weak`: component or co-branding names (Intel, NVIDIA, Leica, Harman Kardon …) chosen only
 *   when no other brand is in the title ("Laptop HP …, Intel Core i5" is HP).
 * - `ambiguous`: also an ordinary word (Arctic, Sapphire, Ninja, Trust …): accepted in a title only
 *   among the first 8 words and not followed by a colour word ("Arctic Grey" is a colour).
 * - `fieldOnly`: never detected in titles (Orange, Total, Ring, Dual …), only from a brand field.
 * - `nameInTitle: false`: the bare name is a common word; only its multi-word aliases count in
 *   titles (Nothing → "Nothing Phone", "CMF by Nothing").
 * - `requiresNext`: the bare name counts in a title only when the next word matches (CAT S75).
 * - `accessoryMaker`: makes only accessories, so it is the offer's brand even when it follows a
 *   compatibility marker ("Suport auto pentru telefon Hoco").
 * Line flags: `next` (the following word must match), `platform` (ignored on game titles: "Joc …
 * PS5"), `device` (ignored on accessory titles: "Husa iPhone 17"), `alone` (only when no other
 * brand is named: Redmi/POCO → Xiaomi).
 */

export interface LineSeed {
  name: string;
  aliases?: readonly string[];
  next?: RegExp;
  platform?: boolean;
  device?: boolean;
  alone?: boolean;
}

export interface BrandSeed {
  name: string;
  slug?: string;
  aliases?: readonly string[];
  lines?: readonly (string | LineSeed)[];
  weak?: boolean;
  ambiguous?: boolean;
  fieldOnly?: boolean;
  nameInTitle?: boolean;
  requiresNext?: RegExp;
  /** Makes only accessories: kept even after "pentru telefon" (it cannot be the target device). */
  accessoryMaker?: boolean;
  /** The bare name followed by one of these words is a feature, not the maker ("Google TV"). */
  featureNext?: RegExp;
}

const dev = (name: string, extra: Partial<LineSeed> = {}): LineSeed => ({
  name,
  device: true,
  ...extra,
});
const plat = (name: string, extra: Partial<LineSeed> = {}): LineSeed => ({
  name,
  device: true,
  platform: true,
  ...extra,
});

