/**
 * Approves a generated report and publishes it to the site (M23 review workflow). Run it only
 * after the checklist in docs/press-kit/review-checklist.md; then commit the files it writes.
 *   pnpm --filter @pretoscop/worker report:approve data/reports/black-friday-2026 --by "Nume Prenume"
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { findRepoRoot } from '@pretoscop/config/env';
import { REPORT_SCHEMA, renderMarkdown, type ReportData } from '@pretoscop/report';

const { values, positionals } = parseArgs({ allowPositionals: true, options: { by: { type: 'string' } } });
const root = findRepoRoot();
const dir = positionals[0] ? resolve(root, positionals[0]) : '';
if (!dir || !existsSync(join(dir, 'report.json')) || !values.by?.trim()) {
  console.error('usage: report:approve <report dir with report.json> --by "Nume Prenume"');
  process.exit(2);
}
const data = JSON.parse(readFileSync(join(dir, 'report.json'), 'utf8')) as ReportData;
if (data.schema !== REPORT_SCHEMA) throw new Error(`unknown report schema ${data.schema}`);
data.approval = { approved: true, by: values.by.trim(), at: new Date().toISOString() };
writeFileSync(join(dir, 'report.json'), `${JSON.stringify(data, null, 1)}\n`);
const charts = existsSync(join(dir, 'charts')) ? readdirSync(join(dir, 'charts')).filter((f) => f.endsWith('.png')).sort() : [];
writeFileSync(join(dir, 'report.md'), renderMarkdown(data, charts.map((f) => ({ file: `charts/${f}`, alt: f.replace(/\.png$/, '').replace(/-/g, ' ') }))));

// Publish: one JSON per report next to the registry, and the registry's import list.
const content = join(root, 'apps/web/src/content/reports');
writeFileSync(join(content, `${data.id}.json`), `${JSON.stringify(data)}\n`);
const ids = readdirSync(content).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
const ident = (id: string) => `r_${id.replace(/[^a-z0-9]/gi, '_')}`;
const block = [
  '// <published:start> (generated by report:approve — do not edit by hand)',
  ...ids.map((id) => `import ${ident(id)} from './${id}.json';`),
  `export const PUBLISHED: ReportData[] = [${ids.map((id) => `${ident(id)} as unknown as ReportData`).join(', ')}];`,
  '// <published:end>',
].join('\n');
const indexPath = join(content, 'index.ts');
const index = readFileSync(indexPath, 'utf8');
writeFileSync(indexPath, index.replace(/\/\/ <published:start>[\s\S]*?\/\/ <published:end>/, block));
console.log(`approved by ${data.approval.by}; published apps/web/src/content/reports/${data.id}.json — commit it with the registry.`);
